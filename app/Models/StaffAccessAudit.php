<?php

namespace App\Models;

use Database\Factories\StaffAccessAuditFactory;
use Illuminate\Database\Eloquent\Attributes\Fillable;
use Illuminate\Database\Eloquent\Factories\HasFactory;
use Illuminate\Database\Eloquent\Model;
use Illuminate\Database\Eloquent\Relations\BelongsTo;

#[Fillable([
    'actor_id',
    'user_id',
    'site',
    'site_identity_id',
    'application_id',
    'reason',
])]
class StaffAccessAudit extends Model
{
    /** @use HasFactory<StaffAccessAuditFactory> */
    use HasFactory;

    /**
     * @return BelongsTo<User, $this>
     */
    public function actor(): BelongsTo
    {
        return $this->belongsTo(User::class, 'actor_id');
    }

    /**
     * @return BelongsTo<User, $this>
     */
    public function user(): BelongsTo
    {
        return $this->belongsTo(User::class);
    }

    /**
     * @return BelongsTo<SiteIdentity, $this>
     */
    public function siteIdentity(): BelongsTo
    {
        return $this->belongsTo(SiteIdentity::class);
    }

    /**
     * @return BelongsTo<Application, $this>
     */
    public function application(): BelongsTo
    {
        return $this->belongsTo(Application::class);
    }
}
